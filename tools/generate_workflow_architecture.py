#!/usr/bin/env python3
"""Generate source-derived Workflow architecture observations."""

from __future__ import annotations

import argparse
import sys
from collections import Counter
from pathlib import Path

from workflow_architecture import discover_workflow_architecture

DESTINATION = Path("docs/policies/architecture-baseline.md")


def render(repository_root: Path) -> str:
    """Render deterministic observations without defining policy."""
    architecture = discover_workflow_architecture(repository_root)
    layer_modules = Counter(
        module_name.split(".", 1)[0]
        for module_name in architecture
        if module_name
    )
    layer_edges = Counter(
        (
            module_name.split(".", 1)[0],
            dependency.split(".", 1)[0],
        )
        for module_name, record in architecture.items()
        if module_name
        for dependency in record.dependencies
        if dependency
    )
    action_count = sum(
        len(record.action_classes) for record in architecture.values()
    )
    codec_count = sum(
        len(record.codec_classes) for record in architecture.values()
    )
    highest_fanout = sorted(
        (
            (len(record.dependencies), module_name)
            for module_name, record in architecture.items()
        ),
        key=lambda item: (-item[0], item[1]),
    )[:10]

    lines = [
        "# Architecture Baseline",
        "",
        "<!-- Generated by tools/generate_workflow_architecture.py. -->",
        "",
        "This file contains source-derived observations only. Normative policy",
        "is human-authored in `workflow-architecture-policy.json`; rationale",
        "is in `architecture-decisions.md`. Generation alters neither.",
        "",
        "## Source inventory",
        "",
        "| Layer | Python modules |",
        "|---|---:|",
    ]
    lines.extend(
        f"| `{layer}` | {layer_modules[layer]} |"
        for layer in sorted(layer_modules)
    )
    lines.extend(
        [
            f"| **Total** | **{len(architecture)}** |",
            "",
            f"Execute-bearing classes observed: **{action_count}**",
            "",
            f"Encode/decode codec candidates observed: **{codec_count}**",
            "",
            "## Observed internal dependency edges",
            "",
            "| Source layer | Target layer | Edges |",
            "|---|---|---:|",
        ]
    )
    lines.extend(
        f"| `{source}` | `{target}` | {layer_edges[(source, target)]} |"
        for source, target in sorted(layer_edges)
    )
    lines.extend(
        [
            "",
            "## Highest observed module fanout",
            "",
            "| Module | Internal dependencies |",
            "|---|---:|",
        ]
    )
    lines.extend(
        f"| `{module_name}` | {fanout} |"
        for fanout, module_name in highest_fanout
    )
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    """Write the baseline or verify that its checked copy is exact."""
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", type=Path, default=Path.cwd())
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    root = arguments.root.resolve()
    destination = root / DESTINATION
    rendered = render(root)
    if arguments.check:
        if not destination.exists() or destination.read_text() != rendered:
            print(
                f"stale architecture baseline: {destination}", file=sys.stderr
            )
            return 1
        return 0
    destination.write_text(rendered)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
